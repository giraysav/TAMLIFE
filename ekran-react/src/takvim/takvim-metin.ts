export function takvimMetin(dil: Dil) {
  return dil === "en" ? EN : TR
}
export type TakvimMetin = ReturnType<typeof takvimMetin>

/** Gun durumu rengi; renk tek basina anlam tasimaz (etiket de gosterilir). */
export const DURUM_RENK: Record<string, string> = {
  calisiyor: "#10b981",
  yillik_izin: "#0ea5e9",
  sirket_izni: "#6366f1",
  raporlu: "#f43f5e",
  arife_tatili: "#f59e0b",
  resmi_tatil: "#8b5cf6",
  hafta_sonu: "#94a3b8",
}
/** Gun kutusunun zemini: durum rengi lejant rengiyle ayni; bolunmus gunde iki renk capraz ikiye; dolu degilse acik ton. */
export function gunZemini(durum: string, durum2: string | null | undefined, dolu: boolean): string {
  const renk = (d: string) => DURUM_RENK[d] ?? "#64748b"
  if (durum2) return `linear-gradient(135deg, ${renk(durum)} 0 50%, ${renk(durum2)} 50% 100%)`
  if (dolu) return renk(durum)
  return `${renk(durum)}24` // calisiyor / hafta sonu: ayni rengin acik tonu
}
